/**
 * The flagship demo trip: twelve days across Tokyo, Hakone, Kyoto, Nara and Osaka for four
 * travellers, departing seven weeks after the seed date.
 *
 * Every coordinate, address and price is a real one. The money is internally consistent by
 * construction: each expense's `amountMinor` is the trip-currency (JPY) total, foreign receipts carry
 * their source amount plus the rate that produced it, and the four travellers' paid totals sum to
 * exactly the same figure as their share totals plus the one unclaimed receipt. That is what makes the
 * costs screen show real balances instead of four zeroes.
 *
 * Every date is `day(n)`, n days from the fixture anchor — see `./anchor.ts`. The trip departs on
 * `day(50)` and lands home on `day(61)`, so it is always seven weeks out and always the workspace's
 * next big thing, whatever calendar day the seed is run on. Planning artefacts that predate it —
 * the deposit, the rail passes, the first two reservations — sit at negative offsets in the same
 * scale, which is what keeps "booked six weeks before departure" true rather than merely typed.
 */

