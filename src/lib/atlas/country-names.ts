/**
 * Country names, frozen into the bundle.
 *
 * `Intl.DisplayNames` looks like the obvious answer and is the wrong one here.
 * The atlas renders on the server first, in workerd, against whatever ICU data
 * that runtime was built with, and then hydrates in the reader's browser against
 * a different one. The two disagree on more codes than is comfortable: `FK` is
 * "Falkland Islands" in one build and "Falkland Islands (Islas Malvinas)" in
 * another, `PS` swings between "Palestine" and "Palestinian Territories", and
 * `CD`, `MM`, `HK` and `MO` each carry a parenthetical in some builds but not in
 * others. A text node that differs between the server pass and the client pass
 * is a hydration error, and a hydration error is a console error, which fails
 * the quality bar outright.
 *
 * So the names live here instead: one table, one spelling, identical on both
 * sides of the wire and stable across every runtime we deploy to. It is also the
 * only way to hold an editorial line ("DR Congo" rather than "Congo - Kinshasa",
 * "Macao" rather than "Macao SAR China") in a product where a country name has
 * to fit a list row on a 360px phone.
 *
 * **Scope.** All 249 officially-assigned ISO 3166-1 alpha-2 codes, plus `XK`
 * (Kosovo), which is user-assigned but carries a bundled outline and is an
 * ordinary destination. Deprecated and exceptionally-reserved codes are
 * deliberately absent: a traveller cannot visit `EU`, and `SU` has not existed
 * since 1991. Spellings follow CLDR's `en-GB` region names, which is the voice
 * the rest of the product's formatters are already pinned to.
 */

