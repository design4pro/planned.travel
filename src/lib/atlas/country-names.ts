/**
 * `JP` to `Japan`.
 *
 * Anything the table does not name - a malformed column, a code retired before
 * we shipped - comes back as the upper-cased code itself rather than an empty
 * string or a thrown error. A record that says `ZZ` is honest and still
 * readable; a record with a blank where its country should be is neither.
 */
export function countryName(code: string): string {
  const upper = code.trim().toUpperCase()
  return COUNTRY_NAMES[upper] ?? upper
}
