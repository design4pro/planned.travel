/**
 * The frozen CLDR tables the multi-locale formatter renders from.
 *
 * `docs/SPEC.md` §8.5 calls cross-runtime agreement the hardest constraint on
 * this build, and this file is where it is paid for. Every date, amount and list
 * is rendered first on the server in workerd and then hydrated in whatever
 * browser the traveller brought. Where the two runtimes disagree about a
 * locale-dependent string, React sees a text-node mismatch: the page falls back
 * to a client render and Safari logs a hydration error on a screen that looked
 * perfect in Chrome. §8.5 calls that a defect, never a tolerance.
 *
 * Every value below was read out of workerd 1.20260815.1 - the runtime that
 * renders first - and diffed against WebKit 26.5 and Chromium 151 across all
 * twenty-three shipped locales. These are the fields that disagreed, and each is
 * now a table lookup rather than a question asked of `Intl`:
 *
 * - `{ month: 'short' }` in `en`: workerd `Sept`, WebKit `Sep`. The original
 *   bug, and the reason `src/lib/format.ts` already carried a table.
 * - `{ month: 'short' }` in `el`: workerd gives the unaccented format forms,
 *   WebKit the accented standalone ones.
 * - `{ month: 'long' }` in `el`: workerd answers a lone month field with the
 *   genitive `Ιανουαρίου`, WebKit with the nominative `Ιανουάριος`. Greek is the
 *   only locale of the twenty-three whose bare `{ month: 'long' }` differs at
 *   all, so `monthsLong` is that bare standalone form everywhere — the name a
 *   month calendar puts over a column — and Greek alone takes the nominative,
 *   which is what all three runtimes also produce in the month-plus-year
 *   context. Deriving the whole column from that composed context instead is a
 *   trap: `ja`, `zh-Hans` and `zh-Hant` write the 月 as a pattern literal rather
 *   than as part of the name, so the month field of `2026年1月` is the bare
 *   digit `1`, and `vi` writes the in-context form in lower case.
 * - `{ weekday: 'short' }` in `ar`, `ca` and `ru`, which disagree about the
 *   definite article, the trailing full stop and the capital respectively.
 * - The abbreviated month *inside* a date in `ca`, whose CLDR form carries its
 *   preposition, and in `ru`, which WebKit widens to the genitive.
 * - The composed short-date pattern in `ar` and `ca`, and the weekday separator
 *   in `de` and `zh-Hans`.
 * - `Intl.RelativeTimeFormat` in `ru` and `zh-Hant`.
 * - `Intl.ListFormat` in `ar`: WebKit wraps every item in U+2068/U+2069 isolate
 *   characters and workerd does not.
 * - `Intl.NumberFormat` currency spacing in `id`, which separates a letter
 *   symbol from the amount in workerd and not in WebKit.
 * - The minor units of `HUF` and `IDR`: workerd says zero digits and WebKit says
 *   two, so the same stored integer renders as two different *amounts*.
 *
 * Chromium agreed with workerd on every one of those fields, which is why a
 * Chromium-only check catches none of them and `e2e/i18n-runtime-parity.spec.ts`
 * runs its comparison in WebKit.
 *
 * Three things are deliberately *not* frozen, because all three were measured
 * byte-identical in the three runtimes for all twenty-three locales: decimal and
 * percent grouping, the currency symbol itself, and the composed
 * `{ month: 'long', year: 'numeric' }` form. They stay live `Intl` calls in
 * `format.ts` and the parity spec re-proves them on every run.
 *
 * Nothing here is translated. These are CLDR facts; the connector words in the
 * open-ended range patterns are the single exception, and English is the only
 * locale that has any - precisely so that no invented translation reaches a
 * screen while the catalogue owns the copy.
 */

import type { Locale } from '#/lib/i18n'

/**
 * One pattern per CLDR plural category. `other` is the only category every
 * locale has, so it is the only required one: a category a locale never selects
 * is absent, and a lookup that misses falls back to `other`.
 */
export type PluralPatterns = { readonly other: string } & {
  readonly [Category in Exclude<Intl.LDMLPluralRule, 'other'>]?: string
}

/** How a locale says "five minutes ago" at each grain the feed uses. */
export interface RelativePatterns {
  /** The zero grain: `just now`, `teraz`, `now`. */
  readonly now: string
  readonly minute: PluralPatterns
  readonly hour: PluralPatterns
  readonly day: PluralPatterns
}

/**
 * The four literals CLDR joins a conjunction list with: the separator before the
 * last item is not the one between the others.
 */
export interface ListPatterns {
  /** Between the two items of a two-item list. */
  readonly pair: string
  /** After the first item of a longer list. */
  readonly start: string
  /** Between the middle items. */
  readonly middle: string
  /** Before the last item. */
  readonly end: string
}

/**
 * How a locale lays money out: `{s}` is the symbol, `{n}` the amount and `{g}`
 * the UTS#35 currency-spacing gap, which goes in unless the character facing the
 * amount is in the Unicode symbol category. That one rule is what makes a glyph
 * symbol sit flush against the figure and a lettered one take a space, in the
 * same locale and from the same template.
 */
export interface CurrencyPatterns {
  readonly positive: string
  readonly negative: string
}

/**
 * The composed date forms. `{d}` is the day, `{M}` the month number, `{MMM}` and
 * `{MMMM}` the abbreviated and wide month names, `{y}` the year and `{E}` the
 * abbreviated weekday.
 */
export interface DatePatterns {
  /** A day alone, for the collapsed half of a range. */
  readonly day: string
  /** Day and month. */
  readonly dayMonth: string
  /** The product's standard date. */
  readonly date: string
  /** Weekday, day and month. */
  readonly weekdayDate: string
  /**
   * A range with no start, and a range with no end. English keeps the words the
   * product already renders; every other locale gets the language-neutral
   * interval dash, because a connector word is authored copy and copy belongs to
   * the catalogue rather than to a CLDR table.
   */
  readonly rangeOpenStart: string
  readonly rangeOpenEnd: string
  /** The same, for a clock range. */
  readonly timeOpenStart: string
}

/** Everything one locale needs, all of it frozen. */
export interface LocaleFormats {
  /**
   * The tag handed to `Intl` for the fields that stay live. `en` resolves to
   * `en-GB`, which is what the product has always pinned and what every current
   * caller's output depends on.
   */
  readonly intlLocale: string
  /** Abbreviated month names, standalone, indexed by `getUTCMonth()`. */
  readonly monthsShort: ReadonlyArray<string>
  /** Wide month names, standalone and nominative, indexed by `getUTCMonth()`. */
  readonly monthsLong: ReadonlyArray<string>
  /** Abbreviated weekday names, standalone, indexed by `getUTCDay()`. */
  readonly weekdaysShort: ReadonlyArray<string>
  /** Wide weekday names, indexed by `getUTCDay()`. */
  readonly weekdaysLong: ReadonlyArray<string>
  /**
   * The abbreviated month as it appears *inside* a date, for the locales that
   * inflect it there. `null` when it is the standalone form.
   */
  readonly monthsShortInDate: ReadonlyArray<string> | null
  /** The same for weekdays, which `de` writes with a full stop inside a date. */
  readonly weekdaysShortInDate: ReadonlyArray<string> | null
  readonly patterns: DatePatterns
  readonly relative: RelativePatterns
  readonly list: ListPatterns
  readonly currency: CurrencyPatterns
}

