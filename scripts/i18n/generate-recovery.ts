import { writeFile } from 'node:fs/promises'
import { format, resolveConfig } from 'prettier'
import { LOCALE_TAGS } from '../../src/lib/i18n/locales'
import type { Catalogue, NamespaceMessages } from '../../src/lib/i18n/types'

// Recovery must survive failure of the lazy namespace imports themselves.
const catalogues: Record<string, Catalogue> = {}
for (const locale of LOCALE_TAGS) {
  const { default: shell }: { default: NamespaceMessages } = await import(
    `../../src/lib/i18n/messages/${locale}/shell.ts`
  )
  const { default: ui }: { default: NamespaceMessages } = await import(
    `../../src/lib/i18n/messages/${locale}/ui.ts`
  )
  catalogues[locale] = Object.fromEntries([
    ...Object.entries(shell)
      .filter(
        ([key]) =>
          key.startsWith('error.') ||
          key.startsWith('session.') ||
          key.startsWith('feedback.') ||
          key === 'nav.homeLink',
      )
      .map(([key, value]) => [`shell.${key}`, value]),
    ['ui.status.working', ui['status.working']],
    ['ui.action.remove', ui['action.remove']],
  ])
}
const source = `// Generated by pnpm exec tsx scripts/i18n/generate-recovery.ts. Do not edit.
import type { Locale } from './locales'
import type { Catalogue } from './types'

export const RECOVERY_CATALOGUES = ${JSON.stringify(catalogues)} as const satisfies Record<Locale, Catalogue>
`
await writeFile(
  new URL('../../src/lib/i18n/recovery-catalogues.ts', import.meta.url),
  await format(source, {
    ...(await resolveConfig(
      new URL('../../src/lib/i18n/recovery-catalogues.ts', import.meta.url),
    )),
    parser: 'typescript',
  }),
)
