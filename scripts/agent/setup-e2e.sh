#!/usr/bin/env bash
# Prepare the e2e environment INSIDE a sandcastle sandbox, mirroring
# .github/actions/e2e-env/action.yml step for step - with one deliberate
# difference: this script also passes Polar sandbox credentials through when
# they are present, so an agent working a billing ticket can reach a real
# checkout. CI does not, and should not: its VITE_POLAR_PRODUCT_* come from
# repository variables holding *production* ids. Run it from the worktree
# root when a ticket needs Playwright; the fast loop (typecheck/lint/vitest)
# never needs it.
#
#   bash scripts/agent/setup-e2e.sh
#   PLAYWRIGHT_BASE_URL=http://127.0.0.1:3030 pnpm e2e [--project=chromium] [-g <spec>]
#
# Basemap: taken from the operator cache (${PLANNED_TRAVEL_CACHE:-~/.cache/planned-travel},
# filled once per host by scripts/agent/fetch-basemap.sh) when .e2e-tiles/ is empty. Only
# when neither exists does it download from R2, which needs (sandcastle/CI only, never cezar):
#   CLOUDFLARE_API_TOKEN   R2:read on planned-travel-tiles (basemap download)
#   CLOUDFLARE_ACCOUNT_ID  account that owns the bucket
#   E2E_TILES_KEY          dated archive key, e.g. basemaps/planet-20260818.pmtiles
#                          Same name CI and the cloud environment use for the same object.
#
# Optional, and only for a ticket that touches billing (all seven or none):
#   POLAR_ACCESS_TOKEN POLAR_WEBHOOK_SECRET POLAR_SERVER
#   VITE_POLAR_PRODUCT_{SOLO,CREW}_{MONTHLY,YEARLY}
# SANDBOX organization credentials only - see the note at the write step below.
# The download is skipped when .e2e-tiles/basemap.pmtiles already exists.
# .e2e-tiles is per checkout; under cezar the setup step seeds it from the
# operator's cache (scripts/agent/fetch-basemap.sh), so a worktree rarely
# downloads.
#
# The dev server runs on :3030 — the reserved automation range playwright.config.ts
# insists on outside CI — and inside the container's own network namespace, so
# parallel sandboxes never collide on it.
set -euo pipefail

PORT="${E2E_PORT:-3030}"
# 127.0.0.1, never localhost: the server binds v4 only, and on this host another checkout's
# `vite dev` sits on [::1]:3010, which "localhost" also resolves to. Run 2272b8e2 saw that server
# answer the readiness probe before its own was up, and the seed then talked to the wrong app.
BASE_URL="http://127.0.0.1:${PORT}"

# --if-needed: fix-loop re-validation reuses the live dev server — HMR/SSR
# reload picks up the fix commits, so a restart buys nothing.
if [ "${1:-}" = "--if-needed" ] && curl -sf -o /dev/null "${BASE_URL}/"; then
  echo "==> dev server already answering on :${PORT} — skipping e2e env setup"
  exit 0
fi

echo "==> .dev.vars (throwaway secrets for this sandbox)"
# This clobbers .dev.vars, which inside a sandbox is nothing: the worktree is
# disposable and the file does not exist yet. On a developer's own checkout it
# is the real secret file - Better Auth's signing key, the Polar tokens, the
# email key - and overwriting it costs an afternoon of finding out which value
# was lost. The two cases are told apart by a marker this script writes itself:
# a .dev.vars without it was written by a person, and is not ours to replace.
SANDBOX_MARKER="# sandcastle throwaway - regenerated by scripts/agent/setup-e2e.sh"
if [ -f .dev.vars ] && ! head -1 .dev.vars | grep -qF "$SANDBOX_MARKER"; then
  echo "ERROR: .dev.vars exists and was not written by this script." >&2
  echo "       This looks like a real checkout rather than a sandbox worktree." >&2
  echo "       Refusing to overwrite it. Run the suite against your own env with:" >&2
  echo "         pnpm dev  # in one shell" >&2
  echo "         pnpm e2e  # in another" >&2
  exit 1
fi
cat > .dev.vars <<EOF
${SANDBOX_MARKER}
BETTER_AUTH_SECRET=$(openssl rand -base64 32)
APP_URL=${BASE_URL}
TILES_ARCHIVE_KEY=basemaps/e2e.pmtiles
EOF

# Billing, when the operator supplied it. All seven names or none: three of them are the
# Worker's (POLAR_*) and four are Vite's (VITE_POLAR_PRODUCT_*), and half a set is the
# failure mode docs/DEPLOY.md §10 warns about - a pricing page that offers one plan and
# breaks the other three with no error.
#
# These must be the SANDBOX organization's. A production token in a disposable container
# reachable by an agent is a live payments credential, and a production product id opens a
# checkout against a real account. Neither fails loudly.
if [ -n "${POLAR_ACCESS_TOKEN:-}" ]; then
  echo "==> Polar sandbox credentials (billing tickets)"
  cat >> .dev.vars <<EOF
POLAR_ACCESS_TOKEN=${POLAR_ACCESS_TOKEN}
POLAR_WEBHOOK_SECRET=${POLAR_WEBHOOK_SECRET:-}
POLAR_SERVER=${POLAR_SERVER:-sandbox}
EOF

  # A separate file, and not a stylistic choice: Vite reads .env.local and Miniflare reads
  # .dev.vars, so a VITE_ name in .dev.vars is silently empty rather than an error.
  if [ -f .env.local ] && ! head -1 .env.local | grep -qF "$SANDBOX_MARKER"; then
    echo "ERROR: .env.local exists and was not written by this script - refusing to overwrite." >&2
    exit 1
  fi
  cat > .env.local <<EOF
${SANDBOX_MARKER}
VITE_POLAR_PRODUCT_SOLO_MONTHLY=${VITE_POLAR_PRODUCT_SOLO_MONTHLY:-}
VITE_POLAR_PRODUCT_SOLO_YEARLY=${VITE_POLAR_PRODUCT_SOLO_YEARLY:-}
VITE_POLAR_PRODUCT_CREW_MONTHLY=${VITE_POLAR_PRODUCT_CREW_MONTHLY:-}
VITE_POLAR_PRODUCT_CREW_YEARLY=${VITE_POLAR_PRODUCT_CREW_YEARLY:-}
EOF

  # An empty id does not break the pricing page - it breaks that one Upgrade button, at the
  # moment somebody presses it. Say so now rather than let an agent discover it as a bug in
  # whatever it was actually working on.
  for name in VITE_POLAR_PRODUCT_SOLO_MONTHLY VITE_POLAR_PRODUCT_SOLO_YEARLY \
              VITE_POLAR_PRODUCT_CREW_MONTHLY VITE_POLAR_PRODUCT_CREW_YEARLY; do
    if [ -z "$(eval "echo \"\${${name}:-}\"")" ]; then
      echo "    WARNING: ${name} is unset - that plan's checkout will refuse." >&2
    fi
  done
else
  echo "==> no Polar credentials in the environment - checkout will refuse, everything else runs"
fi

echo "==> route tree"
pnpm generate-routes

echo "==> local D1 migrations"
pnpm db:migrate:local

# Operator cache first: a cezar worktree never holds the R2 token, so the archive
# is fetched once per host (scripts/agent/fetch-basemap.sh) and linked from here.
CACHE_TILES="${PLANNED_TRAVEL_CACHE:-$HOME/.cache/planned-travel}/e2e-tiles/basemap.pmtiles"
if [ ! -s .e2e-tiles/basemap.pmtiles ] && [ -s "$CACHE_TILES" ]; then
  echo "==> basemap linked from the operator cache (${CACHE_TILES})"
  mkdir -p .e2e-tiles
  ln -sf "$CACHE_TILES" .e2e-tiles/basemap.pmtiles
fi

if [ ! -s .e2e-tiles/basemap.pmtiles ]; then
  NO_BASEMAP="no basemap: run scripts/agent/fetch-basemap.sh once on this host (or set E2E_TILES_KEY + CLOUDFLARE_* for a direct R2 download)"
  echo "==> basemap not in the shared cache — downloading from R2 (${E2E_TILES_KEY:?$NO_BASEMAP})"
  : "${CLOUDFLARE_API_TOKEN:?$NO_BASEMAP}"
  : "${CLOUDFLARE_ACCOUNT_ID:?$NO_BASEMAP}"
  mkdir -p .e2e-tiles
  # The cache is shared and survives this worktree, so a half-written file here
  # would poison every later run — the -s test above only checks non-empty —
  # and two parallel sandboxes can miss the cache at the same time. Download to
  # a per-process temp file and move it into place: mv within one filesystem is
  # atomic, so basemap.pmtiles is either absent or complete, and a race costs
  # one wasted transfer instead of a corrupt basemap.
  tmp=".e2e-tiles/basemap.pmtiles.$$.part"
  trap 'rm -f "$tmp"' EXIT
  pnpm exec wrangler r2 object get \
    "planned-travel-tiles/${E2E_TILES_KEY}" \
    --remote --file "$tmp"
  mv -f "$tmp" .e2e-tiles/basemap.pmtiles
  trap - EXIT
else
  echo "==> basemap present in .e2e-tiles (shared cache) — skipping download"
fi

echo "==> loading the archive into the local R2 simulator"
pnpm exec wrangler r2 object put \
  planned-travel-tiles/basemaps/e2e.pmtiles \
  --local --file .e2e-tiles/basemap.pmtiles \
  --content-type application/octet-stream

echo "==> dev server on :${PORT}"
# Loopback only: on the cezar host this port is shared with the operator's LAN,
# and Node's fetch (seed.mjs) resolves localhost to 127.0.0.1, so the v4 bind
# is exactly what the seed and Playwright need. nohup + the pid file let a
# caller that is itself a short-lived step (cez-setup.sh) leave the server
# running and let cez-handback.sh stop it later.
# 4 GB of heap: the default (~2 GB on this node) is what a dev server serving SSR + the optimizer
# to four browsers for twenty minutes runs out of - dev-server.log ending in `JavaScript heap out
# of memory` and a rung of ECONNREFUSED specs (run 20260830-3, issue #117, attempt 3). The ladder's
# probe now reports that as infra rather than as a red branch; this makes it rare as well.
#
# E2E=1 is what vite.config.ts reads to turn the devtools console relay off. Without it the
# Worker's own console.error lines - the seeded sign-up's auth email dead-letters here, because
# this .dev.vars carries no EMAIL_API_KEY - are streamed into whichever browser page Playwright
# happens to have open, and the spec holding that page fails on someone else's background error.
# Scoped to this one process on purpose: the seed and everything after it must not see it, and a
# developer's own `pnpm dev` keeps the relay.
mkdir -p .agent
E2E=1 NODE_OPTIONS="${NODE_OPTIONS:-} --max-old-space-size=4096" \
  nohup pnpm exec vite dev --port "${PORT}" --strictPort --host 127.0.0.1 > dev-server.log 2>&1 &
echo $! > .agent/dev-server.pid
for _ in $(seq 1 60); do
  if curl --silent --fail --output /dev/null "${BASE_URL}/"; then
    echo "dev server up"
    break
  fi
  # --strictPort makes vite exit when 127.0.0.1:PORT is already taken. With the process gone
  # there is nothing to wait for, and whatever answers on that port next is not this checkout.
  if ! kill -0 "$(cat .agent/dev-server.pid)" 2>/dev/null; then
    echo "ERROR: dev server exited before answering on :${PORT}; is the port held by another checkout?" >&2
    tail -50 dev-server.log >&2
    exit 1
  fi
  sleep 2
done
if ! curl --silent --fail --output /dev/null "${BASE_URL}/"; then
  echo "ERROR: dev server did not answer on :${PORT} within 120s" >&2
  tail -50 dev-server.log >&2
  exit 1
fi

echo "==> seeding the demo workspace"
node scripts/seed/seed.mjs --url "${BASE_URL}"
node scripts/seed/verify.mjs

echo
echo "Ready. Run the suite with:"
echo "  PLAYWRIGHT_BASE_URL=${BASE_URL} pnpm e2e"
